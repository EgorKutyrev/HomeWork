n = int(input())
ones = ['', 'одно', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять']
teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать']
tens = ['', '', 'двадцать', 'тридцать', 'сорок']
if 10 <= n <= 19:
    text = teens[n - 10]
elif n == 20:
    text = 'двадцать'
elif n == 30:
    text = 'тридцать'
elif n == 40:
    text = 'сорок'
else:
    t = n // 10
    o = n % 10
    text = tens[t] + ' ' + ones[o]
if n % 10 == 1 and n != 11:
    text += ' учебное задание'
elif n % 10 in (2, 3, 4) and n not in (12, 13, 14):
    text += ' учебных задания'
else:
    text += ' учебных заданий'
print(text)